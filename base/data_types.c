#include <stdio.h>

int main() {
  int age = 25;
  float height = 1.75;
  char initial = 'A';

  printf("Int Age: %d\n", age);
  printf("float height: %f\n", height);
  printf("float height 1: %.1f\n", height);
  printf("float height 2: %.2f\n", height);
  printf("char initial: %c\n", initial);

  return 0;
}
